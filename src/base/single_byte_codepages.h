// Windows DBCS pages decode an isolated lead byte to the page's default
// character. The remaining high bytes form contiguous single-byte ranges.
struct ByteRange {
    u8 first;
    u8 last;
    u16 unicode_start;
};

constexpr HighBytes dbcs_high_bytes(u16 default_char, std::initializer_list<ByteRange> ranges) {
    HighBytes table{};
    table.fill(default_char);
    for (const auto& range : ranges) {
        for (u32 byte = range.first; byte <= range.last; ++byte) {
            table[byte - 0x80] = static_cast<u16>(range.unicode_start + byte - range.first);
        }
    }
    return table;
}

